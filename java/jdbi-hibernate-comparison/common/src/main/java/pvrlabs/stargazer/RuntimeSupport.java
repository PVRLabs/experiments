package pvrlabs.stargazer;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;

import io.avaje.jex.Jex;

import java.util.Arrays;
import java.util.List;
import java.util.Map;
import java.util.concurrent.Executors;
import java.util.concurrent.TimeUnit;

public final class RuntimeSupport {
    public static String env(String key, String fallback) {
        return System.getenv().getOrDefault(key, fallback);
    }

    public static List<String> repositories() {
        return Arrays.stream(
                        env(
                                        "APP_GITHUB_REPOS",
                                        "PVRLabs/statlite,PVRLabs/aibadger,scriptella/scriptella-etl")
                                .split(","))
                .map(String::trim)
                .filter(repository -> !repository.isEmpty())
                .distinct()
                .limit(4)
                .toList();
    }

    public static HikariDataSource datasource() {
        var config = new HikariConfig();
        config.setJdbcUrl(env("DB_URL", "jdbc:h2:file:./data/starsdb"));
        config.setUsername("sa");
        config.setPassword("");
        config.setMaximumPoolSize(4);
        config.setMinimumIdle(1);
        return new HikariDataSource(config);
    }

    // Match the reference entity schema; schema work remains part of application startup.
    public static void schema(HikariDataSource source) {
        try (var connection = source.getConnection();
                var statement = connection.createStatement()) {
            statement.execute(
                    "create table if not exists projects(id bigint generated by default as identity primary key,"
                            + "repo_name varchar(255) not null unique,"
                            + "current_stars integer,"
                            + "current_forks integer,"
                            + "current_watchers integer,"
                            + "last_pushed_at timestamp(6) with time zone,"
                            + "last_polled_at timestamp(6) with time zone)");
            statement.execute(
                    "create table if not exists star_history(id bigint generated by default as identity primary key,"
                            + "project_id bigint not null"
                            + " references projects(id),"
                            + "star_count integer not null,"
                            + "recorded_at timestamp(6) with time zone not null)");
        } catch (java.sql.SQLException failure) {
            throw new IllegalStateException(failure);
        }
    }

    public static void routes(Jex jex, Store store, javax.sql.DataSource source) {
        jex.get("/diagnostics", context -> context.json(Diagnostics.snapshot(source)));
        var repositories = repositories();
        var pollService =
                new PollService(
                        store,
                        new Github(
                                env("APP_GITHUB_API_BASE_URL", "http://127.0.0.1:18080"),
                                env("GITHUB_TOKEN", "")),
                        repositories);
        var dashboard = new DashboardController(store, repositories);
        var views = new Views();
        jex.get(
                "/",
                context -> {
                    // Resolve chart associations before the persistence scope closes.
                    var model =
                            store.transaction(
                                    () -> {
                                        try {
                                            return dashboard.dashboard();
                                        } catch (Exception failure) {
                                            throw new IllegalStateException(failure);
                                        }
                                    });
                    context.html(views.render(model));
                });
        jex.post(
                "/refresh",
                context -> {
                    pollService.pollAll();
                    context.redirect("/");
                });
        jex.get(
                "/ready",
                context -> {
                    try (var connection = source.getConnection();
                            var statement = connection.createStatement();
                            var result = statement.executeQuery("select count(*) from projects")) {
                        result.next();
                        context.json(Map.of("status", "UP"));
                    }
                });
        // Keep a scheduler in every variant; the harness controls the initial delay.
        var scheduler = Executors.newSingleThreadScheduledExecutor();
        scheduler.scheduleAtFixedRate(
                () -> {
                    try {
                        pollService.pollAll();
                    } catch (RuntimeException failure) {
                        System.getLogger("scheduler")
                                .log(System.Logger.Level.ERROR, "Poll cycle failed", failure);
                    }
                },
                Long.parseLong(env("APP_GITHUB_INITIAL_DELAY_MS", "300000")),
                Long.parseLong(env("APP_GITHUB_POLL_INTERVAL_MS", "300000")),
                TimeUnit.MILLISECONDS);
        jex.lifecycle().onShutdown(scheduler::shutdownNow);
    }
}
