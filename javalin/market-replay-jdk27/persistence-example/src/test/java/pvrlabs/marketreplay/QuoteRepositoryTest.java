package pvrlabs.marketreplay;

import static org.junit.jupiter.api.Assertions.*;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;
import org.jdbi.v3.core.Jdbi;
import org.junit.jupiter.api.Test;
import pvrlabs.repository.RepositoryContext;

class QuoteRepositoryTest {
    @Test void failedInsertRollsBackEarlierRows() {
        var db = new RepositoryContext(Jdbi.create("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1"), "h2");
        db.useHandle(h -> h.execute("CREATE TABLE quote_samples (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, fetched_at TIMESTAMP NOT NULL, cycle INT NOT NULL, sample_index INT NOT NULL, market_time VARCHAR(20) NOT NULL, symbol VARCHAR(20) NOT NULL, price DECIMAL(12,2) NOT NULL)"));
        var repo = new QuoteRepository(db);
        var batch = new QuoteBatch(0, "09:30", 0, List.of(
                new FixtureQuote("AAPL", new BigDecimal("1.00")),
                new FixtureQuote("GOOG", null),
                new FixtureQuote("NVDA", new BigDecimal("3.00"))));
        assertThrows(org.jdbi.v3.core.statement.UnableToExecuteStatementException.class,
                () -> repo.insert(Instant.parse("2026-10-27T15:00:00Z"), batch));
        assertEquals(0, repo.count());
    }
}
