package lab;

import java.math.BigDecimal;
import java.util.List;

import org.apache.ibatis.annotations.Arg;
import org.apache.ibatis.annotations.ConstructorArgs;
import org.apache.ibatis.annotations.Insert;
import org.apache.ibatis.annotations.Param;
import org.apache.ibatis.annotations.Select;
import org.apache.ibatis.annotations.Update;

public interface QuoteMapper {
    String CREATE_TABLE = """
        CREATE TABLE IF NOT EXISTS quotes (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            batch_seq INTEGER NOT NULL,
            cycle INTEGER NOT NULL,
            sample_index INTEGER NOT NULL,
            market_time VARCHAR(5) NOT NULL,
            symbol VARCHAR(8) NOT NULL,
            price DECIMAL(12,4) NOT NULL,
            UNIQUE(batch_seq,symbol)
        )
        """;

    String LATEST_OR_HISTORY = """
        SELECT batch_seq,cycle,sample_index,market_time,symbol,price
        FROM quotes
        WHERE symbol=#{symbol}
        ORDER BY id DESC
        LIMIT #{limit}
        """;

    String INSERT = """
        INSERT INTO quotes(batch_seq,cycle,sample_index,market_time,symbol,price)
        VALUES(#{sequence},#{cycle},#{sampleIndex},#{marketTime},#{symbol},#{price})
        """;

    @Update(CREATE_TABLE)
    int createTable();

    @Update("CREATE INDEX IF NOT EXISTS quotes_symbol ON quotes(symbol,id DESC)")
    int createIndex();

    @Select("SELECT COUNT(*) FROM quotes")
    int count();

    @Select("SELECT 1")
    int probe();

    @Select("""
        SELECT SETTING_NAME || '=' || SETTING_VALUE
        FROM INFORMATION_SCHEMA.SETTINGS
        WHERE SETTING_NAME IN ('CACHE_SIZE','WRITE_DELAY')
        """)
    List<String> h2Settings();

    @Select(LATEST_OR_HISTORY)
    @ConstructorArgs({
        @Arg(column="batch_seq", javaType=int.class),
        @Arg(column="cycle", javaType=int.class),
        @Arg(column="sample_index", javaType=int.class),
        @Arg(column="market_time", javaType=String.class),
        @Arg(column="symbol", javaType=String.class),
        @Arg(column="price", javaType=BigDecimal.class)
    })
    Quote selectQuotes(@Param("symbol") String symbol, @Param("limit") int limit);

    @Select(LATEST_OR_HISTORY)
    @ConstructorArgs({
        @Arg(column="batch_seq", javaType=int.class),
        @Arg(column="cycle", javaType=int.class),
        @Arg(column="sample_index", javaType=int.class),
        @Arg(column="market_time", javaType=String.class),
        @Arg(column="symbol", javaType=String.class),
        @Arg(column="price", javaType=BigDecimal.class)
    })
    List<Quote> selectHistory(@Param("symbol") String symbol, @Param("limit") int limit);

    @Insert(INSERT)
    int insert(
        @Param("sequence") int sequence,
        @Param("cycle") int cycle,
        @Param("sampleIndex") int sampleIndex,
        @Param("marketTime") String marketTime,
        @Param("symbol") String symbol,
        @Param("price") BigDecimal price);

    @Select("SELECT COUNT(*),MAX(batch_seq),SUM(price) FROM quotes")
    @ConstructorArgs({
        @Arg(column="COUNT(*)", javaType=int.class),
        @Arg(column="MAX(BATCH_SEQ)", javaType=int.class),
        @Arg(column="SUM(PRICE)", javaType=BigDecimal.class)
    })
    QuoteState state();
}
