public final class Quotes {
    public static final List<String> SYMBOLS = List.of("AAPL", "GOOG", "NVDA");
    public record Quote(int sequence, int cycle, int sampleIndex, String marketTime, String symbol, BigDecimal price) {}
    public record Batch(Integer sequence, Integer cycle, Integer sampleIndex, String marketTime, Map<String, BigDecimal> prices) {}
    private final HikariDataSource ds;
    public Quotes(HikariDataSource ds) throws Exception {
        this.ds = ds;
        try (var c = ds.getConnection(); var s = c.createStatement()) {
            s.execute("CREATE TABLE IF NOT EXISTS quotes (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, batch_seq INTEGER NOT NULL, cycle INTEGER NOT NULL, sample_index INTEGER NOT NULL, market_time VARCHAR(5) NOT NULL, symbol VARCHAR(8) NOT NULL, price DECIMAL(12,4) NOT NULL, UNIQUE(batch_seq,symbol))");
            s.execute("CREATE INDEX IF NOT EXISTS quotes_symbol ON quotes(symbol,id DESC)");
            try (var r = s.executeQuery("SELECT COUNT(*) FROM quotes")) {
                r.next();
                if (r.getInt(1) == 0) seed(c);
            }
            try (var r = s.executeQuery("SELECT 1")) { if (!r.next()) throw new SQLException("DB probe failed"); }
            try (var r = s.executeQuery("SELECT SETTING_NAME,SETTING_VALUE FROM INFORMATION_SCHEMA.SETTINGS WHERE SETTING_NAME IN ('CACHE_SIZE','WRITE_DELAY')")) {
                while (r.next()) System.out.println("H2 " + r.getString(1) + "=" + r.getString(2));
            }
        }
        System.out.printf("Hikari min=%d max=%d connectionTimeout=%d validationTimeout=%d idleTimeout=%d maxLifetime=%d keepaliveTime=%d initializationFailTimeout=%d%n", ds.getMinimumIdle(), ds.getMaximumPoolSize(), ds.getConnectionTimeout(), ds.getValidationTimeout(), ds.getIdleTimeout(), ds.getMaxLifetime(), ds.getKeepaliveTime(), ds.getInitializationFailTimeout());
    }
    public static HikariDataSource dataSource() {
        var ds = new HikariDataSource();
        ds.setJdbcUrl("jdbc:h2:file:" + System.getProperty("run.dir") + "/quotes;CACHE_SIZE=4096;DB_CLOSE_ON_EXIT=FALSE");
        ds.setUsername("sa"); ds.setPassword(""); ds.setMinimumIdle(1); ds.setMaximumPoolSize(2);
        ds.setConnectionTimeout(3000); ds.setValidationTimeout(1000); return ds;
    }
    private void seed(Connection c) throws Exception {
        c.setAutoCommit(false);
        try (var reader = new BufferedReader(new InputStreamReader(Objects.requireNonNull(Quotes.class.getResourceAsStream("/quotes.csv"))));
             var p = c.prepareStatement("INSERT INTO quotes(batch_seq,cycle,sample_index,market_time,symbol,price) VALUES(?,?,?,?,?,?)")) {
            reader.readLine(); String line; int i=0;
            while ((line=reader.readLine())!=null) {
                var row=line.split(","); p.setInt(1,i/3); p.setInt(2,0); p.setInt(3,i/3);
                p.setString(4,row[0]); p.setString(5,row[1]); p.setBigDecimal(6,new BigDecimal(row[2])); p.addBatch(); i++;
            }
            if (i!=1170) throw new IllegalStateException("Wrong fixture size " + i);
            p.executeBatch(); c.commit();
        } catch (Exception e) { c.rollback(); throw e; } finally { c.setAutoCommit(true); }
    }
    private Quote row(ResultSet r) throws SQLException { return new Quote(r.getInt(1),r.getInt(2),r.getInt(3),r.getString(4),r.getString(5),r.getBigDecimal(6)); }
    public List<Quote> latest() throws SQLException {
        var rows=new ArrayList<Quote>();
        try (var c=ds.getConnection(); var p=c.prepareStatement("SELECT batch_seq,cycle,sample_index,market_time,symbol,price FROM quotes WHERE symbol=? ORDER BY id DESC LIMIT 1")) {
            for (String symbol:SYMBOLS) { p.setString(1,symbol); try (var r=p.executeQuery()) { if(r.next()) rows.add(row(r)); } }
        } return rows;
    }
    public List<Quote> history(String symbol, int limit) throws SQLException {
        if (!SYMBOLS.contains(symbol) || limit<1 || limit>390) throw new IllegalArgumentException("Invalid symbol/limit");
        var rows=new ArrayList<Quote>();
        try(var c=ds.getConnection();var p=c.prepareStatement("SELECT batch_seq,cycle,sample_index,market_time,symbol,price FROM quotes WHERE symbol=? ORDER BY id DESC LIMIT ?")) {
            p.setString(1,symbol);p.setInt(2,limit);try(var r=p.executeQuery()){while(r.next()) rows.add(row(r));}
        } Collections.reverse(rows);return rows;
    }
    public Map<String,Integer> insert(Batch b) throws SQLException {
        if(b==null || b.sequence()==null || b.sequence()<390 || b.cycle()==null || b.cycle()<1 || b.sampleIndex()==null || b.sampleIndex()<0 || b.sampleIndex()>389 || b.marketTime()==null || !b.marketTime().matches("(?:09:[3-5][0-9]|1[0-5]:[0-5][0-9])") || b.prices()==null || !b.prices().keySet().equals(Set.copyOf(SYMBOLS))) throw new IllegalArgumentException("Invalid batch");
        for (var price:b.prices().values()) if(price==null || price.signum()<=0 || price.scale()>4 || price.compareTo(new BigDecimal("100000000"))>=0) throw new IllegalArgumentException("Invalid price");
        try(var c=ds.getConnection()) {
            c.setAutoCommit(false);
            try(var p=c.prepareStatement("INSERT INTO quotes(batch_seq,cycle,sample_index,market_time,symbol,price) VALUES(?,?,?,?,?,?)")) {
                for(var symbol:SYMBOLS){p.setInt(1,b.sequence());p.setInt(2,b.cycle());p.setInt(3,b.sampleIndex());p.setString(4,b.marketTime());p.setString(5,symbol);p.setBigDecimal(6,b.prices().get(symbol));p.addBatch();}
                p.executeBatch();c.commit();
            } catch(SQLException e){c.rollback();throw e;} finally {c.setAutoCommit(true);}
        } return Map.of("sequence",b.sequence());
    }
    public Map<String,Object> state() throws SQLException {
        try(var c=ds.getConnection();var s=c.createStatement();var r=s.executeQuery("SELECT COUNT(*),MAX(batch_seq),SUM(price) FROM quotes")) {r.next();return Map.of("rows",r.getInt(1),"maxSequence",r.getInt(2),"priceSum",r.getBigDecimal(3));}
    }
}
