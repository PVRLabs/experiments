package lab;

import com.zaxxer.hikari.HikariDataSource;
import java.io.BufferedReader;
import java.io.IOException;
import java.io.StringReader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.BatchUpdateException;
import java.sql.SQLException;
import java.sql.Statement;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.LocalCacheScope;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;

public final class FixtureRecoveryCheck {
    private static void check(boolean condition, String message) {
        if (!condition) throw new AssertionError(message);
    }

    public static void main(String[] args) throws Exception {
        var directory = Path.of(args[0]).toAbsolutePath();
        Files.createDirectories(directory);
        try (var ds = new HikariDataSource()) {
            ds.setJdbcUrl("jdbc:h2:file:" + directory.resolve("quotes")
                + ";CACHE_SIZE=4096;DB_CLOSE_ON_EXIT=FALSE");
            ds.setUsername("sa");
            ds.setPassword("");
            ds.setMinimumIdle(1);
            ds.setMaximumPoolSize(2);
            ds.setConnectionTimeout(3000);
            ds.setValidationTimeout(1000);
            try (var connection = ds.getConnection(); var statement = connection.createStatement()) {
                statement.execute("""
                    CREATE TABLE quotes (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        batch_seq INTEGER NOT NULL, cycle INTEGER NOT NULL,
                        sample_index INTEGER NOT NULL, market_time VARCHAR(5) NOT NULL,
                        symbol VARCHAR(8) NOT NULL, price DECIMAL(12,4) NOT NULL,
                        UNIQUE(batch_seq,symbol))
                    """);
            }
            var config = new Configuration(new Environment("h2", new JdbcTransactionFactory(), ds));
            config.setLocalCacheScope(LocalCacheScope.STATEMENT);
            config.addMapper(QuoteMapper.class);
            var sessions = new SqlSessionFactoryBuilder().build(config);
            var repository = new MyBatisQuoteRepository(sessions);
            String fixture;
            try (var stream = FixtureRecoveryCheck.class.getResourceAsStream("/quotes.csv")) {
                fixture = new String(stream.readAllBytes(), StandardCharsets.UTF_8);
            }
            var lines = new java.util.ArrayList<>(fixture.lines().toList());
            check(lines.size() == 1171, "Fixture line count");
            lines.set(lines.size() - 1, "15:59,GOOG,228.29");
            try (var reader = new BufferedReader(new StringReader(String.join("\n", lines)))) {
                MyBatisQuoteRepository.loadFixture(sessions, reader);
                throw new AssertionError("Expected late fixture duplicate to fail");
            } catch (RuntimeException expected) {
                boolean conflict = false;
                boolean earlierRowsAccepted = false;
                for (Throwable cause = expected; cause != null; cause = cause.getCause()) {
                    if (cause instanceof SQLException sql && "23505".equals(sql.getSQLState())) {
                        conflict = true;
                    }
                    if (cause instanceof BatchUpdateException batch) {
                        for (int count : batch.getUpdateCounts()) {
                            if (count > 0 || count == Statement.SUCCESS_NO_INFO) earlierRowsAccepted = true;
                        }
                    }
                }
                check(conflict && earlierRowsAccepted, "Late failure after accepted batch rows");
            }
            check(repository.state().rows() == 0, "No partial fixture after late duplicate");
            check(ds.getHikariPoolMXBean().getActiveConnections() == 0, "Released failed-batch connection");

            try (var reader = new BufferedReader(new StringReader(fixture)) {
                private int linesRead;
                @Override public String readLine() throws IOException {
                    if (++linesRead == 500) throw new IOException("Injected fixture read failure");
                    return super.readLine();
                }
            }) {
                MyBatisQuoteRepository.loadFixture(sessions, reader);
                throw new AssertionError("Expected fixture I/O failure");
            } catch (IOException | RuntimeException expected) {
                boolean ioFailure = false;
                for (Throwable cause = expected; cause != null; cause = cause.getCause()) {
                    if (cause instanceof IOException) ioFailure = true;
                }
                check(ioFailure, "Injected read failure must propagate");
            }
            check(repository.state().rows() == 0, "No partial fixture after I/O failure");
            check(ds.getHikariPoolMXBean().getActiveConnections() == 0, "Released fixture connection");
            repository.initialize(ds);
            check(repository.state().rows() == 1170, "Normal initialization recovers full fixture");
            check(repository.latest().size() == 3, "Recovered latest quotes");
            check(repository.history("AAPL", 390).size() == 390, "Recovered history");
        }
        System.out.println("PASS: late fixture rollback, I/O failure, resource cleanup, initialization recovery");
    }
}
