package lab;

import com.zaxxer.hikari.HikariDataSource;
import org.jdbi.v3.core.Handle;
import org.jdbi.v3.core.Jdbi;
import org.jdbi.v3.core.statement.PreparedBatch;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStreamReader;
import java.math.BigDecimal;
import java.nio.charset.StandardCharsets;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.Collections;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Objects;
import java.util.function.Supplier;

public final class JdbiQuoteRepository implements QuoteRepository {
    private static final String SELECT = """
        SELECT batch_seq,cycle,sample_index,market_time,symbol,price
        FROM quotes WHERE symbol=:symbol ORDER BY id DESC LIMIT :limit
        """;
    private static final String INSERT = """
        INSERT INTO quotes(batch_seq,cycle,sample_index,market_time,symbol,price)
        VALUES(:sequence,:cycle,:sampleIndex,:marketTime,:symbol,:price)
        """;
    private final Jdbi jdbi;

    public JdbiQuoteRepository(Jdbi jdbi) {
        this.jdbi = Objects.requireNonNull(jdbi);
        jdbi.registerRowMapper(Quote.class, (rs, ctx) -> new Quote(
            rs.getInt("batch_seq"), rs.getInt("cycle"), rs.getInt("sample_index"),
            rs.getString("market_time"), rs.getString("symbol"), rs.getBigDecimal("price")));
    }

    public void initialize(HikariDataSource ds) throws IOException {
        jdbi.useHandle(handle -> {
            handle.execute("""
                CREATE TABLE IF NOT EXISTS quotes (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    batch_seq INTEGER NOT NULL,
                    cycle INTEGER NOT NULL,
                    sample_index INTEGER NOT NULL,
                    market_time VARCHAR(5) NOT NULL,
                    symbol VARCHAR(8) NOT NULL,
                    price DECIMAL(12,4) NOT NULL,
                    UNIQUE(batch_seq,symbol)
                )
                """);
            handle.execute("CREATE INDEX IF NOT EXISTS quotes_symbol ON quotes(symbol,id DESC)");
            if (handle.createQuery("SELECT COUNT(*) FROM quotes").mapTo(Integer.class).one() == 0) {
                try (var stream = Objects.requireNonNull(getClass().getResourceAsStream("/quotes.csv"));
                     var reader = new BufferedReader(new InputStreamReader(stream, StandardCharsets.UTF_8))) {
                    loadFixture(handle, reader);
                }
            }
            if (handle.createQuery("SELECT 1").mapTo(Integer.class).one() != 1) {
                throw new IllegalStateException("DB probe failed");
            }
            handle.createQuery("""
                SELECT SETTING_NAME,SETTING_VALUE FROM INFORMATION_SCHEMA.SETTINGS
                WHERE SETTING_NAME IN ('CACHE_SIZE','WRITE_DELAY')
                """)
                .map((rs, ctx) -> "H2 " + rs.getString(1) + "=" + rs.getString(2))
                .list().forEach(System.out::println);
        });
        System.out.printf(
            "Hikari min=%d max=%d connectionTimeout=%d validationTimeout=%d idleTimeout=%d maxLifetime=%d keepaliveTime=%d initializationFailTimeout=%d%n",
            ds.getMinimumIdle(), ds.getMaximumPoolSize(), ds.getConnectionTimeout(),
            ds.getValidationTimeout(), ds.getIdleTimeout(), ds.getMaxLifetime(),
            ds.getKeepaliveTime(), ds.getInitializationFailTimeout());
    }

    static void loadFixture(Handle handle, BufferedReader reader) throws IOException {
        handle.useTransaction(tx -> {
            reader.readLine();
            String line;
            int i = 0;
            try (var batch = tx.prepareBatch(INSERT)) {
                while ((line = reader.readLine()) != null) {
                    var row = line.split(",");
                    bind(batch, i / 3, 0, i / 3, row[0], row[1], new BigDecimal(row[2]));
                    i++;
                }
                if (i != 1170) throw new IllegalStateException("Wrong fixture size " + i);
                batch.execute();
            }
        });
    }

    private static void bind(PreparedBatch batch, int sequence, int cycle, int index,
                             String time, String symbol, BigDecimal price) {
        batch.bind("sequence", sequence).bind("cycle", cycle).bind("sampleIndex", index)
            .bind("marketTime", time).bind("symbol", symbol).bind("price", price).add();
    }

    public static RepositoryFailure translate(Throwable cause) {
        var seen = Collections.newSetFromMap(new IdentityHashMap<Throwable, Boolean>());
        for (Throwable t = cause; t != null && seen.add(t); t = t.getCause()) {
            if (t instanceof SQLException sql) {
                String state = sql.getSQLState();
                return new RepositoryFailure(
                    state != null && state.startsWith("23")
                        ? RepositoryFailure.Kind.CONFLICT : RepositoryFailure.Kind.UNEXPECTED,
                    cause);
            }
        }
        return new RepositoryFailure(RepositoryFailure.Kind.UNEXPECTED, cause);
    }

    private <T> T operation(Supplier<T> action) {
        try {
            return action.get();
        } catch (RepositoryFailure e) {
            throw e;
        } catch (RuntimeException e) {
            throw translate(e);
        }
    }

    @Override
    public List<Quote> latest() {
        return operation(() -> jdbi.withHandle(handle -> {
            var rows = new ArrayList<Quote>(QuoteBatch.SYMBOLS.size());
            for (var symbol : QuoteBatch.SYMBOLS) {
                handle.createQuery(SELECT).bind("symbol", symbol).bind("limit", 1)
                    .mapTo(Quote.class).findOne().ifPresent(rows::add);
            }
            return rows;
        }));
    }

    @Override
    public List<Quote> history(String symbol, int limit) {
        QuoteBatch.validateHistory(symbol, limit);
        return operation(() -> jdbi.withHandle(handle -> {
            var rows = handle.createQuery(SELECT).bind("symbol", symbol).bind("limit", limit)
                .mapTo(Quote.class).list();
            Collections.reverse(rows);
            return rows;
        }));
    }

    @Override
    public void insert(QuoteBatch batch) {
        if (batch == null) throw new IllegalArgumentException("Invalid batch");
        batch.validate();
        operation(() -> {
            jdbi.useTransaction(handle -> {
                try (var insert = handle.prepareBatch(INSERT)) {
                    for (var symbol : QuoteBatch.SYMBOLS) {
                        bind(insert, batch.sequence(), batch.cycle(), batch.sampleIndex(),
                            batch.marketTime(), symbol, batch.prices().get(symbol));
                    }
                    insert.execute();
                }
            });
            return null;
        });
    }

    @Override
    public QuoteState state() {
        return operation(() -> jdbi.withHandle(handle ->
            handle.createQuery("""
                SELECT COUNT(*),COALESCE(MAX(batch_seq),0),COALESCE(SUM(price),0)
                FROM quotes
                """)
                .map((rs, ctx) -> new QuoteState(rs.getInt(1), rs.getInt(2), rs.getBigDecimal(3)))
                .one()));
    }
}
