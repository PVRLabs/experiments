DROP ALL OBJECTS;

CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    current_forks INTEGER,
    current_stars INTEGER,
    current_watchers INTEGER,
    last_polled_at TIMESTAMP(6) WITH TIME ZONE,
    last_pushed_at TIMESTAMP(6) WITH TIME ZONE,
    repo_name CHARACTER VARYING(255) NOT NULL UNIQUE
);

CREATE TABLE star_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recorded_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    star_count INTEGER NOT NULL,
    project_id BIGINT NOT NULL,
    CONSTRAINT fk_star_history_project
        FOREIGN KEY (project_id) REFERENCES projects(id)
);

